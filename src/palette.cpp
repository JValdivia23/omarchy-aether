QStringList Palette::chromaticNames() { return {"red", "green", "yellow", "blue", "magenta", "cyan"}; }
QStringList Palette::ansiNames() {
    return {"background", "red", "green", "yellow", "blue", "magenta", "cyan", "foreground", "muted",
            "bright_red", "bright_green", "bright_yellow", "bright_blue", "bright_magenta", "bright_cyan", "bright_foreground"};
}

Palette Palette::create(const QColor &seed, const QColor &surface) {
    Palette p;
    p.source = seed.name();
    const auto source = Color::toLch(seed), neutral = Color::toLch(surface);
    const double hue = source.c < .015 ? 270 : source.h;
    const double bgLightness = std::clamp(neutral.l, .20, .23);
    auto put = [&](const QString &name, const QColor &c) { p.colors[name] = c.name(); };
    auto bg = [&](const QString &name, double lightness) {
        put(name, Color::fromLch({lightness, .016, hue}));
    };
    bg("background", bgLightness);
    bg("dark_background", bgLightness - .03);
    bg("darker_background", bgLightness - .065);
    bg("lighter_background", bgLightness + .04);
    bg("selection", bgLightness + .06);
    const QList<QColor> surfaces{QColor(p.colors["background"]), QColor(p.colors["lighter_background"]), QColor(p.colors["selection"])};
    auto text = [&](const QString &name, Color::Lch color, double ratio = 4.8) {
        put(name, Color::readable(color, surfaces, ratio));
    };
    text("foreground", {.79, .026, hue}, 7.0);
    text("light_foreground", {.83, .024, hue}, 7.5);
    text("bright_foreground", {.88, .025, hue}, 8.0);
    text("dark_foreground", {.65, .020, hue});
    text("muted", {.63, .018, hue});
    text("accent", {.74, std::clamp(source.c, .10, .16), hue});

    // Tokyo Night supplies the role structure, not a palette to recolor into one dominant hue.
    // A bounded shared shift preserves the gaps between semantic hue families.
    const double shift = source.c < .015 ? 0 : 6 * std::sin(hue * M_PI / 180);
    const double saturation = std::clamp(.94 + source.c * .5, .96, 1.08);
    struct Role { const char *name; double l, c, h, bright; };
    const Role roles[] = {{"red", .73, .159, 10, .045}, {"green", .79, .140, 130, .075},
                          {"yellow", .79, .110, 75, .045}, {"blue", .73, .133, 262, .045},
                          {"magenta", .72, .132, 303, .050}, {"cyan", .70, .105, 209, .065}};
    for (const auto &r : roles) {
        text(r.name, {r.l, r.c * saturation, r.h + shift});
        auto regular = Color::toLch(QColor(p.colors[r.name]));
        text(QString("bright_") + r.name, {std::min(.92, regular.l + r.bright), r.c * saturation, r.h + shift});
    }
    text("orange", {.77, .12, 48 + shift});
    text("brown", {.67, .06, 45 + shift});
    return p;
}

Palette Palette::fromToml(const QByteArray &contents, QString *error) {
    Palette result;
    const QRegularExpression entry(R"re(^\s*([a-z_]+)\s*=\s*"(#[0-9a-fA-F]{6})"\s*(?:#.*)?$)re");
    int lineNumber = 0;
    for (const QString &line : QString::fromUtf8(contents).split('\n')) {
        ++lineNumber;
        const QString clean = line.trimmed();
        if (clean.isEmpty() || clean.startsWith('#') || clean == "mode = \"dark\"") continue;
        const auto match = entry.match(line);
        if (!match.hasMatch() || result.colors.contains(match.captured(1))) {
            *error = QString("Invalid or duplicate palette entry on line %1.").arg(lineNumber);
            return {};
        }
        result.colors[match.captured(1)] = match.captured(2).toLower();
    }
    return result;
}

QByteArray Palette::toml() const {
    QByteArray out = "# Generated by omarchy-aether. Runtime data; do not symlink into dotfiles.\nmode = \"dark\"\n\n";
    const QStringList order{"accent", "selection", "muted", "background", "dark_background", "darker_background", "lighter_background",
                            "foreground", "dark_foreground", "light_foreground", "bright_foreground", "red", "yellow", "orange",
                            "green", "cyan", "blue", "magenta", "brown", "bright_red", "bright_yellow", "bright_green",
                            "bright_cyan", "bright_blue", "bright_magenta"};
    for (const auto &name : order) out += name.toUtf8() + " = \"" + colors.value(name).toUtf8() + "\"\n";
    return out;
}

QJsonObject Palette::report() const {
    QJsonArray checks;
    bool valid = true;
    auto check = [&](const QString &name, double value, double minimum) {
        const bool passed = value + 1e-6 >= minimum;
        checks.append(QJsonObject{{"name", name}, {"value", value}, {"minimum", minimum}, {"passed", passed}});
        valid = valid && passed;
    };
    QStringList required = ansiNames();
    required << "accent" << "selection" << "dark_background" << "darker_background" << "lighter_background"
             << "dark_foreground" << "light_foreground" << "orange" << "brown";
    for (const auto &name : required) {
        if (!QRegularExpression("^#[0-9a-fA-F]{6}$").match(colors.value(name)).hasMatch()) {
            return {{"valid", false}, {"error", QString("Missing or invalid color: %1").arg(name)}, {"checks", checks}};
        }
    }
    double minimumText = std::numeric_limits<double>::max();
    const QStringList surfaces{"background", "lighter_background", "selection"};
    QStringList textNames = chromaticNames();
    textNames << "foreground" << "light_foreground" << "bright_foreground" << "dark_foreground" << "muted" << "accent" << "orange" << "brown";
    for (const auto &name : chromaticNames()) textNames << "bright_" + name;
    for (const auto &fg : textNames) {
        for (const auto &bg : surfaces) {
            const double ratio = Color::contrast(QColor(colors[fg]), QColor(colors[bg]));
            minimumText = std::min(minimumText, ratio);
            check(fg + "/" + bg, ratio, 4.5);
        }
    }
    const double body = Color::contrast(QColor(colors["foreground"]), QColor(colors["background"]));
    check("body_text", body, 7.0);
    QSet<QString> unique;
    for (const auto &name : ansiNames()) unique.insert(colors[name]);
    check("unique_ansi_colors", unique.size(), 16);
    double separation = std::numeric_limits<double>::max();
    const auto names = chromaticNames();
    for (int i = 0; i < names.size(); ++i) {
        for (int j = i + 1; j < names.size(); ++j) {
            const double d = Color::distance(QColor(colors[names[i]]), QColor(colors[names[j]]));
            separation = std::min(separation, d);
            check(names[i] + "/" + names[j] + "/distance", d, 7.5);
        }
        check(names[i] + "/bright/distance", Color::distance(QColor(colors[names[i]]), QColor(colors["bright_" + names[i]])), 3.0);
    }
    QJsonObject values;
    for (auto it = colors.begin(); it != colors.end(); ++it) values.insert(it.key(), it.value());
    return {{"valid", valid}, {"source", source}, {"colors", values}, {"checks", checks},
            {"metrics", QJsonObject{{"body_contrast", body}, {"minimum_text_contrast", minimumText},
                                    {"minimum_color_distance", separation}, {"unique_ansi_colors", unique.size()}}},
            {"measurement", "WCAG 2 relative-luminance ratios; opaque sRGB surfaces. Color distances are OKLab Euclidean distance multiplied by 100."}};
}
